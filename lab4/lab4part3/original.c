#include <stdio.h>

#define MAX_CELLS 12
#define LOW_LIMIT 3.60

int main(void)
{
    double volts[MAX_CELLS];
    int n = 0;
    double v;

    /* ---- read the voltages ---- */
    printf("Enter up to %d cell voltages (-1 to stop):\n", MAX_CELLS);
    while (n < MAX_CELLS && scanf("%lf", &v) == 1 && v != -1) {
        volts[n] = v;
        n++;
    }

    if (n == 0) {
        printf("No data.\n");
        return 1;
    }

    /* ---- print the voltages ---- */
    for (int i = 0; i < n; i++) {
        printf("Cell %2d: %.2f V\n", i + 1, volts[i]);
    }

    /* ---- mean ---- */
    double sum = 0.0;
    for (int i = 0; i < n; i++) {
        sum += volts[i];
    }
    double mean = sum / n;

    /* ---- first cell below the limit, -1 if none ---- */
    int weak = -1;
    for (int i = 0; i < n; i++) {
        if (volts[i] < LOW_LIMIT) {
            weak = i;
            break;
        }
    }

    /* ---- summary ---- */
    printf("Cells: %d\n", n);
    printf("Mean: %.3f V\n", mean);
    if (weak < 0) {
        printf("No cell below %.2f V. Status: OK\n", LOW_LIMIT);
    } else {
        printf("Cell %d is below %.2f V. Status: CHECK PACK\n", weak + 1, LOW_LIMIT);
    }
    return 0;
}
